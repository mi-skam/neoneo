"""Build layout/option-de.tsv from a dump of Apple's German layout.

usage: swift tools/dump-layout.swift com.apple.keylayout.German > layout/apple-german.tsv
       python3 tools/option-table.py layout/apple-german.tsv layout/option-de.tsv

Rows are keyed by the German layer-1 character: char, Option, Shift+Option.
Keys whose layer-1 output is not a printable character are skipped; when two
keys share a layer-1 character, the lower key code (main block) wins.
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import Dict

INVISIBLE = {"": "<none>", " ": "<space>", " ": "<nbsp>", " ": "<nnbsp>", "­": "<shy>"}


def decode(field: str) -> str:
    return "".join(chr(int(p, 16)) for p in field.split("U+") if p)


def printable(s: str) -> bool:
    return len(s) == 1 and ord(s) >= 0x20 and ord(s) != 0x7F and not 0xF700 <= ord(s) <= 0xF8FF


def encode(s: str) -> str:
    return INVISIBLE.get(s, s)


def main(dump: str, out: str) -> None:
    by_code: Dict[int, Dict[str, str]] = {}
    for line in Path(dump).read_text(encoding="utf-8").splitlines():
        code, mods, field = line.split("\t")
        by_code.setdefault(int(code), {})[mods] = decode(field)
    rows: Dict[str, str] = {}
    for code in sorted(by_code):
        maps = by_code[code]
        base = maps["none"]
        if not printable(base) or base in rows:
            continue
        rows[base] = "\t".join([encode(base), encode(maps["option"]), encode(maps["shift+option"])])
    header = ["# char\toption\tshift_option", "# Generated by tools/option-table.py from com.apple.keylayout.German."]
    Path(out).write_text("\n".join(header + list(rows.values())) + "\n", encoding="utf-8")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(*sys.argv[1:])
